#!/usr/bin/env python3
"""
Generate endpoint tests from OpenAPI spec.

This script parses the OpenAPI spec and generates pytest tests that verify:
- All endpoints have corresponding SDK methods
- Request parameters are properly typed
- Response schemas are handled correctly
"""

import re
import sys
from pathlib import Path
from typing import Any

import yaml

# Map OpenAPI tags to SDK resource names
TAG_TO_RESOURCE: dict[str, str] = {
    "Posts": "posts",
    "Accounts": "accounts",
    "Profiles": "profiles",
    "Analytics": "analytics",
    "Account Groups": "account_groups",
    "Queue": "queue",
    "Webhooks": "webhooks",
    "API Keys": "api_keys",
    "Media": "media",
    "Tools": "tools",
    "Users": "users",
    "Usage": "usage",
    "Logs": "logs",
    "Connect": "connect",
    "Reddit Search": "reddit",
    "Invites": "invites",
    "GMB Reviews": "accounts",
    "LinkedIn Mentions": "accounts",
}


def camel_to_snake(name: str) -> str:
    """Convert camelCase to snake_case."""
    name = name.replace("-", "_")
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z\d])([A-Z])", r"\1_\2", name)
    return name.lower()


def load_openapi_spec(spec_path: Path) -> dict:
    """Load and parse the OpenAPI spec."""
    with open(spec_path) as f:
        return yaml.safe_load(f)


def extract_endpoints(spec: dict) -> list[dict[str, Any]]:
    """Extract endpoint information from OpenAPI spec."""
    endpoints = []

    for path, path_item in spec.get("paths", {}).items():
        for method, operation in path_item.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue

            tags = operation.get("tags", [])
            if not tags:
                continue

            tag = tags[0]
            if tag not in TAG_TO_RESOURCE:
                continue

            resource_name = TAG_TO_RESOURCE[tag]
            operation_id = operation.get("operationId", "")
            if not operation_id:
                continue

            method_name = camel_to_snake(operation_id)

            # Extract path parameters
            path_params = []
            for param in operation.get("parameters", []):
                if param.get("in") == "path":
                    path_params.append({
                        "name": camel_to_snake(param["name"]),
                        "type": param.get("schema", {}).get("type", "string"),
                        "required": param.get("required", True),
                    })

            # Extract query parameters
            query_params = []
            for param in operation.get("parameters", []):
                if param.get("in") == "query":
                    query_params.append({
                        "name": camel_to_snake(param["name"]),
                        "type": param.get("schema", {}).get("type", "string"),
                        "required": param.get("required", False),
                    })

            # Check if it has a request body
            has_body = "requestBody" in operation

            endpoints.append({
                "resource": resource_name,
                "method": method_name,
                "operation_id": operation_id,
                "http_method": method.upper(),
                "path": path,
                "path_params": path_params,
                "query_params": query_params,
                "has_body": has_body,
            })

    return endpoints


def generate_test_file(endpoints: list[dict[str, Any]]) -> str:
    """Generate the test file content."""
    lines = [
        '"""',
        'Auto-generated endpoint tests from OpenAPI spec.',
        '',
        'DO NOT EDIT THIS FILE MANUALLY.',
        'Run `python scripts/generate_endpoint_tests.py` to regenerate.',
        '"""',
        '',
        'from unittest.mock import MagicMock, patch',
        '',
        'import pytest',
        '',
        'from late import Late',
        '',
        '',
        'class TestEndpointMethods:',
        '    """Test that all SDK methods exist and are callable."""',
        '',
        '    @pytest.fixture',
        '    def client(self) -> Late:',
        '        """Create a test client."""',
        '        return Late(api_key="test_key")',
        '',
    ]

    # Group endpoints by resource
    by_resource: dict[str, list[dict]] = {}
    for endpoint in endpoints:
        resource = endpoint["resource"]
        if resource not in by_resource:
            by_resource[resource] = []
        by_resource[resource].append(endpoint)

    # Generate tests for each resource
    for resource, resource_endpoints in sorted(by_resource.items()):
        lines.append(f'    # {resource.replace("_", " ").title()} methods')

        for endpoint in resource_endpoints:
            method = endpoint["method"]
            lines.append(f'    def test_{resource}_{method}_exists(self, client: Late) -> None:')
            lines.append(f'        """Test that {resource}.{method} method exists."""')
            lines.append(f'        assert hasattr(client.{resource}, "{method}")')
            lines.append(f'        assert callable(client.{resource}.{method})')
            lines.append('')

    # Generate mock response tests
    lines.append('')
    lines.append('class TestEndpointResponses:')
    lines.append('    """Test endpoint response handling with mocked HTTP."""')
    lines.append('')
    lines.append('    @pytest.fixture')
    lines.append('    def client(self) -> Late:')
    lines.append('        """Create a test client."""')
    lines.append('        return Late(api_key="test_key")')
    lines.append('')

    # Generate a sample test for a GET endpoint
    get_endpoints = [e for e in endpoints if e["http_method"] == "GET" and not e["path_params"]]
    if get_endpoints:
        endpoint = get_endpoints[0]
        resource = endpoint["resource"]
        method = endpoint["method"]
        lines.append(f'    @patch("late.client.base.httpx.Client.request")')
        lines.append(f'    def test_{resource}_{method}_response(self, mock_request: MagicMock, client: Late) -> None:')
        lines.append(f'        """Test {resource}.{method} handles response correctly."""')
        lines.append('        mock_response = MagicMock()')
        lines.append('        mock_response.status_code = 200')
        lines.append('        mock_response.json.return_value = {"success": True}')
        lines.append('        mock_response.raise_for_status = MagicMock()')
        lines.append('        mock_request.return_value = mock_response')
        lines.append('')
        lines.append(f'        result = client.{resource}.{method}()')
        lines.append('        assert result == {"success": True}')
        lines.append('')

    return '\n'.join(lines)


def main():
    script_dir = Path(__file__).parent
    spec_path = script_dir.parent / "openapi.yaml"
    output_path = script_dir.parent / "tests" / "test_endpoints_generated.py"

    spec = load_openapi_spec(spec_path)
    endpoints = extract_endpoints(spec)

    if "--print" in sys.argv:
        print(generate_test_file(endpoints))
    else:
        output_path.write_text(generate_test_file(endpoints))
        print(f"Generated {output_path}")
        print(f"Total endpoints: {len(endpoints)}")


if __name__ == "__main__":
    main()
